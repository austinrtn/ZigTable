    const allocator = std.testing.allocator;
    const io = std.testing.io;
    
    const Table = ZigTable(&.{
        .{
            .field_type = []const u8,
            .id = "name",
            .display_name = "Name",
            .fmt_type = .string,
            .padding = 8,
            .alignment = .left,
        },
        .{
            .field_type = u8,
            .id = "age", 
            .display_name = "Age",
            .fmt_type = .number, 
            .padding = 3,
            .alignment = .right,
        },
    });

    var table: Table = .init(allocator);
