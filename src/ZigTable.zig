        fn getRecordStorageEnum(comptime field_enum: FieldEnum) RecordStorage.InnerFieldEnum {
            const tag = @tagName(field_enum);
            return std.meta.stringToEnum(RecordStorage.InnerFieldEnum, tag)
                orelse @compileError("Could not convert FieldEnum to RecordStorage.InnerFieldEnum");
        }
        
        fn getFmtStorageEnum(comptime field_enum: FieldEnum) FmtStorage.InnerFieldEnum {
            const tag = @tagName(field_enum);
            return std.meta.stringToEnum(RecordStorage.InnerFieldEnum, tag)
                orelse @compileError("Could not convert FieldEnum to FmtStorage.InnerFieldEnum");
        }
    };
}

pub fn getFormats(comptime fields: []const TableFieldEntry) [fields.len][]const u8{
        var fmts: [fields.len][]const u8 = @splat(undefined);

        for(fields, 0..) |field, i| { 
            const fmt = &fmts[i];
             fmt.* = Formatting.Format(.{ 
                .format_type = field.fmt_type,
                .alignment = field.alignment,
                .perscision = false,
                .modifier = .none,
            }); 
        }
        return fmts;
}

pub fn getFieldEnum(comptime fields: []const TableFieldEntry) type {
    var names: [fields.len][]const u8 = undefined;
    var values: [fields.len]u8 = undefined;
    
    for(0..fields.len) |i| {
        names[i] = fields[i].id;
        values[i] = @intCast(i);
    }
    
    return @Enum(
        u8,
        .exhaustive, 
        &names, 
        &values,
    );
}

pub fn getRecordType(comptime fields: []const TableFieldEntry, comptime nullable: bool) type {
    var names: [fields.len][]const u8 = undefined;
    var types: [fields.len]type = undefined;
    var attrs: [fields.len]std.builtin.Type.StructField.Attributes = undefined;
    
    for (fields, 0..) |item, i| {
        names[i] = item.id;
        types[i] = blk: {
            if(nullable) break :blk ?item.field_type
            else break :blk item.field_type;
        };
        attrs[i] = blk: {
            if(nullable) break :blk .{.default_value_ptr = &@as(types[i], null) }
            else break :blk .{};
        };
    }
    
    return @Struct(
        .auto,
        null,
        &names,
        &types,
        &attrs,
    );
}

const FmtCell = struct {
    const Self = @This();
    buf: []u8 = undefined, 
    len: usize = 0,

    fn init(allocator: std.mem.Allocator) !Self {
        var self: Self = .{};
        
        self.buf = try allocator.alloc(u8, 0);
        return self; 
    } 

    fn deinit(self: *Self, allocator: std.mem.Allocator) void {
        allocator.free(self.buf);
    }

    fn setValue(self: *Self, val: []u8, allocator: std.mem.Allocator) !void {
        if(val.len > self.buf.len) self.buf = try allocator.realloc(self.buf, val.len);
        @memcpy(self.buf[0..val.len], val);
        self.len = val.len;
    }

    fn getValue(self: Self) []u8 {
        return self.buf[0..self.len];
    }

    fn resize(self: *Self, allocator: std.mem.Allocator, new_size: usize) !void {
        self.buf = try allocator.alloc(u8, new_size);
    }
};

fn getFmtStorage(comptime T: type) type {
    const fields = std.meta.fields(T);
    
    var names: [fields.len][]const u8 = undefined;
    var types: [fields.len]type = undefined;
    var attrs: [fields.len]std.builtin.Type.StructField.Attributes = undefined;
    
    for (fields, 0..) |item, i| {
        names[i] = item.name;
        types[i] = FmtCell;
        attrs[i] = .{};
    }
    
    return @Struct(
        .auto,
        null,
        &names,
        &types,
        &attrs,
    );
}

