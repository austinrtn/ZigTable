pub fn ZigTable(comptime fields: []const TableFieldEntry) type {
    const formats = getFormats(fields);
    return struct {
        const Self = @This();
        /// An enum generated from the `fields` 
        /// paramter.  The enum name equates to the TableFieldEntry's id.  
        /// This enum is used to modify field options 
        /// such as padding and display name. 
        pub const FieldEnum = getFieldEnum(fields);
        
        /// A datatype generated by the `fields` paramter
        /// which refers to a single object containing data for each field.
        pub const Record = getRecordType(fields, false);
        
        /// A datatype generated by the `fields` paramter
        /// which refers to a single object containing data for each field, but
        /// each field is nullable.  Primarly used for altering already 
        /// stored data within the table
        const SetRecord = getRecordType(fields, true);

        /// The unique ID of a stored record.
        pub const RecordId = usize;
        const RecordStorage = SmartSoa(Record);
        const FmtStorage = SmartSoa(getFmtStorage(Record));
        
        impl: struct {
            allocator: std.mem.Allocator,
            record_storage: RecordStorage,
            fmt_storage: FmtStorage, 

            field_options: [fields.len]TableField = @splat(undefined),
            record_map: std.StringHashMap(RecordId) = undefined,
            next_record_id: RecordId = 0,
            heap_record_map_keys: ArrayList([]const u8) = .empty,
            record_writers: ArrayList(Writer) = .empty,
            table_writer: Writer = undefined,
        },

        pub fn init(allocator: std.mem.Allocator) Self {
             var self: Self = .{ .impl = .{ 
                 .allocator = allocator, 
                 .record_storage = .init(),
                 .fmt_storage = .init(),
             }};
             self.impl.record_map = .init(allocator);
             self.impl.table_writer = .init(allocator);

             inline for(0..fields.len) |i| { 
                 const field_opt = &self.impl.field_options[i];
                 field_opt.* = fields[i].getTableField();
                 
                 if(field_opt.display_name.len == 0) 
                    field_opt.display_name = field_opt.id;
             }
             
             return self;
        }

        pub fn deinit(self: *Self) void {
            const impl = &self.impl;
            const allocator = impl.allocator;
            
            impl.fmt_storage.deinit(allocator);
            impl.record_storage.deinit(allocator);
            impl.record_map.deinit();
            
            for(impl.record_writers.items) |*writer| writer.deinit();
            for(impl.heap_record_map_keys.items) |*name| allocator.free(name.*);

            impl.record_writers.deinit(allocator);
            impl.heap_record_map_keys.deinit(allocator);
            impl.table_writer.deinit();
        }

        pub fn output(self: *Self) []const u8{
            return self.impl.table_writer.written();
        }

        pub fn allocCaptureOutput(self: *Self, allocator: std.mem.Allocator) ![]const u8{
            return try allocator.dupe(u8, self.impl.table_writer.written());
        }

        pub fn bufCaptureOutput(self: *Self, buf: []u8) ![]const u8 {
            const out = self.impl.table_writer.written();
            if(buf.len < out.len) return error.NoSpaceLeft;

            const dest = buf[0..out.len];
            @memcpy(dest, out);
            return dest;
        }

        pub fn printStdout(self: *Self, io: std.Io, buf: []u8) !void {
            const out = self.impl.table_writer.written();
            var stdout = std.Io.File.Writer.init(.stdout(), io, buf);
            const writer = &stdout.interface;
            
            try writer.writeAll("\x1b[2J\x1b[H");
            try writer.print("{s}", .{out});
            try writer.flush();
        } 

        pub fn addRecord(self: *Self, record_name: ?[]const u8, record: Record) !RecordId {
            const impl = &self.impl;
            const id = impl.next_record_id;
            const next_id = try std.math.add(RecordId, id, 1);
            
            const name = if (record_name) |provided|
                try impl.allocator.dupe(u8, provided)
            else
                try std.fmt.allocPrint(impl.allocator, "rec_{d}", .{id});
            errdefer impl.allocator.free(name);

            const res = try impl.record_map.getOrPut(name);
            if (res.found_existing) return error.recordExists;
            errdefer _ = impl.record_map.remove(name);
            res.value_ptr.* = id;

            try impl.record_storage.append(impl.allocator, record);
            errdefer _ = impl.record_storage.pop();
            try impl.heap_record_map_keys.append(impl.allocator, name);
            errdefer _ = impl.heap_record_map_keys.pop();

            try impl.record_writers.append(impl.allocator, .init(impl.allocator));
            errdefer _ = impl.record_writers.pop();

            impl.next_record_id = next_id;

            try impl.fmt_storage.append(impl.allocator, FmtCell.init(impl.allocator));
            return id;
        }

        pub fn getRecordIdByName(self: *Self, name: []const u8) !RecordId {
            return self.impl.record_map.get(name) orelse return error.NoRecordFound;
        }

        pub fn getRecordById(self: *Self, id: RecordId) Record {
            return self.impl.record_storage.get(id);
        }

        pub fn getRecordByName(self: *Self, name: []const u8) !Record {
            const id = try self.getRecordIdByName(name);
            return self.getRecordById(id);
        }

        pub fn setRecordByName(self: *Self, name: []const u8, record: SetRecord) !void {
            const id = try self.getRecordIdByName(name);
            try self.setRecordById(id, record);
        }

        pub fn setRecordById(self: *Self, id: RecordId, record: SetRecord) !void {
            var old_record = self.impl.record_storage.get(id); 
            
            inline for(std.meta.fields(SetRecord)) |field | {
                if(@field(record, field.name)) |val| {
                    @field(old_record, field.name) = val;
                }
            }
            
            self.impl.record_storage.set(old_record, id);
        }
        
        pub fn build(self: *Self) !void {
            std.debug.assert(
                self.impl.record_storage.len == self.impl.record_writers.items.len
            );

            try self.fmtText();

            const table_writer = &self.impl.table_writer;
            const t_writer = &table_writer.writer;
            const fmt_storage = &self.impl.fmt_storage;
            const rec_writers = &self.impl.record_writers;

            table_writer.clearRetainingCapacity();
            for(rec_writers.items) |*writer| writer.clearRetainingCapacity();

            try self.buildFields();
            inline for(comptime std.meta.tags(FieldEnum), 0..) |field_enum, i| {
                const items = fmt_storage.items(getRecordStorageEnum(field_enum));

                for(items, rec_writers.items) |item, *rec_writer| {
                    const writer = &rec_writer.writer;
                    try writer.print("{s}", .{item});

                    if(i == fields.len - 1) {
                        try writer.print("\n", .{});
                        try t_writer.print("{s}", .{rec_writer.written()});
                    }
                }
            }
        }

        fn fmtText(self: *Self) !void {
            const impl = &self.impl;
            const rec_storage = &impl.record_storage;
            const fmt_storage = &impl.fmt_storage;
            
            inline for(0..fields.len) |i| {
                const fmt = formats[i];
                const field_opt = impl.field_options[i];
                const field_enum: FieldEnum = @enumFromInt(i);
                const raw_vals = rec_storage.items(getRecordStorageEnum(field_enum));

                for(raw_vals, 0..) |raw, k| {
                    var buf: [256]u8 = undefined;
                    const fmted = try std.fmt.bufPrint(
                        &buf, 
                        fmt, 
                        .{.v = raw, .w = field_opt.padding}, 
                    );
                    try fmt_storage.setValue(getFmtStorageEnum(field_enum), k, fmted);
                } 
            }
        }

        fn buildFields(self: *Self) !void {
            const table_writer = &self.impl.table_writer;
            const t_writer = &table_writer.writer;
            var char_len: usize = 0;

            inline for(0..fields.len) |i| {
                const field_opt = self.impl.field_options[i];
                const display_name = field_opt.display_name;
                const padding = field_opt.padding;
                
                const fmt_opt: FormatOptions = .{
                    .format_type = .string,
                    .alignment = fields[i].alignment,
                    .modifier = .none,
                    .perscision = false,
                };
                
                var buf: [256]u8 = undefined;
                const val = try std.fmt.bufPrint(
                    &buf, 
                    Formatting.Format(fmt_opt), 
                    .{.v = display_name, .w = padding}
                );
                
                char_len += val.len;
                _ = try t_writer.write(val);
            }
            
            try t_writer.print("\n", .{});
            for(0..char_len) |_| _ = try t_writer.write("‾");
            try t_writer.print("\n", .{});
        }

